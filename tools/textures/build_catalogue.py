"""Write src/render/materials/catalogue.ts and docs/assets/TEXTURE_CATALOGUE.md from the processed library.
   python3 tools/textures/build_catalogue.py /tmp/tex/processed.json"""
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from library_meta import META
proc = {p['name']: p for p in json.load(open(sys.argv[1]))}
root = os.path.join(os.path.dirname(__file__), '..', '..')
missing = set(proc) - set(META); assert not missing, missing
lines = ["// Generated by tools/textures/build_catalogue.py from the owner's texture library. Do not edit by hand.",
         "", "export interface LibraryEntry {", "  /** Metres covered by one repeat. */", "  tile: number;", "  /** Width / height of the image (most are square). */", "  aspect: number;",
         "  /** Average colour, linear RGB: used to tint a texture to a wanted colour without losing its detail. */", "  avg: [number, number, number];",
         "  category: string;", "  metal: boolean;", "  alpha: boolean;", "}", "", "export const LIBRARY = {"]
for n in sorted(proc):
    p = proc[n]; c, tile, look, use = META[n]
    lines.append(f"  {n}: {{ tile: {tile}, aspect: {round(p['size'][0]/p['size'][1],3)}, avg: [{p['avgLinear'][0]}, {p['avgLinear'][1]}, {p['avgLinear'][2]}], category: '{c}', metal: {'true' if 'Metalness' in p['maps'] else 'false'}, alpha: {'true' if p['alpha'] else 'false'} }},")
lines += ["} as const satisfies Record<string, LibraryEntry>;", "", "export type LibraryName = keyof typeof LIBRARY;", ""]
open(os.path.join(root, 'src/render/materials/catalogue.ts'), 'w').write('\n'.join(lines))
cats = {}
for n in sorted(proc): cats.setdefault(META[n][0], []).append(n)
md = ["# Texture catalogue", "", f"The owner's texture library (`StreetFightUK-assets/texturesforgame`): {len(proc)} material sets, all from ambientCG (CC0), 1K source.",
      "Each set is stored in `public/textures/lib/` at 512 px as three files: `_c` (colour), `_n` (normal, OpenGL) and `_orm` (ambient occlusion, roughness and metalness packed into red, green and blue).",
      "The game loads a set only when something uses it. Where each one is used is in `docs/assets/TEXTURE_ASSIGNMENTS.md`.", "",
      "Maps: C colour, N normal, R roughness, M metalness, AO ambient occlusion, D displacement (in the source only; not shipped), O opacity, E emission.", ""]
order = ['brick', 'stone', 'concrete', 'asphalt', 'paving', 'grass', 'ground', 'tile-floor', 'tile-wall', 'porcelain', 'wood', 'wood-floor', 'wood-paint', 'fabric', 'carpet', 'leather', 'plastic', 'metal', 'metal-paint', 'metal-rust', 'facade', 'foliage']
short = {'Color': 'C', 'NormalGL': 'N', 'NormalDX': None, 'Roughness': 'R', 'Metalness': 'M', 'AmbientOcclusion': 'AO', 'Displacement': 'D', 'Opacity': 'O', 'Emission': 'E', 'Scattering': 'S'}
for c in order:
    if c not in cats: continue
    md += [f"## {c} ({len(cats[c])})", "", "| Set | Looks like | Suits | Source size | Maps | One repeat |", "|---|---|---|---|---|---|"]
    for n in cats[c]:
        p = proc[n]; _, tile, look, use = META[n]
        maps = ' '.join(x for x in (short.get(k) for k in p['maps']) if x)
        md.append(f"| {n} | {look} | {use} | {p['src'][0]}×{p['src'][1]} | {maps} | {tile} m |")
    md.append("")
open(os.path.join(root, 'docs/assets/TEXTURE_CATALOGUE.md'), 'w').write('\n'.join(md))
print(len(proc), {c: len(v) for c, v in cats.items()})
