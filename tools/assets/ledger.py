#!/usr/bin/env python3
"""
The asset production ledger.

Each work package records what it has done in docs/assets/ledger/<package>.json
(a list of entries, one per spreadsheet row it touched). This script merges
them, writes docs/assets/ASSET_MANIFEST.md and the statistics in
docs/assets/ASSET_PROGRESS.md, and ticks "Got it" in docs/ASSETS_NEEDED.csv and
.xlsx for every row whose entry is status "done" (sourced or made, integrated
into the game and tested). Nothing else in the workbook changes.

Entry fields (JSON):
  id        Game id, exactly as in the spreadsheet        (required)
  area      Area, exactly as in the spreadsheet           (required; id+area is the key)
  status    "done" | "partial" | "todo" | "blocked"       (required)
  parts     what was delivered, e.g. {"model": "done", "icon": "todo"}
  files     final paths in the repo
  format    e.g. "GLB", "WebP", "JSON clip", "MP3"
  source    URL, pack name, or "original"
  licence   e.g. "CC0 1.0"
  origin    "downloaded" | "original"
  optimised, integrated, tested   true/false
  notes     anything a reviewer should know

Run: python3 tools/assets/ledger.py [--check]
"""
import csv, glob, json, os, sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, 'docs', 'ASSETS_NEEDED.csv')
XLSX = os.path.join(ROOT, 'docs', 'ASSETS_NEEDED.xlsx')
LEDGER = os.path.join(ROOT, 'docs', 'assets', 'ledger')
OUT = os.path.join(ROOT, 'docs', 'assets')


def rows():
    with open(CSV, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def entries():
    out = {}
    problems = []
    for path in sorted(glob.glob(os.path.join(LEDGER, '*.json'))):
        pkg = os.path.splitext(os.path.basename(path))[0]
        for e in json.load(open(path, encoding='utf-8')):
            key = (e['area'], e['id'])
            if key in out:
                problems.append(f'{key} recorded by both {out[key]["package"]} and {pkg}')
            e['package'] = pkg
            out[key] = e
    return out, problems


def main():
    rs = rows()
    known = {(r['Area'], r['Game id']) for r in rs}
    es, problems = entries()
    for k in es:
        if k not in known:
            problems.append(f'{k} is not a row in the spreadsheet')
    done = {k for k, e in es.items() if e['status'] == 'done' and e.get('integrated') and e.get('tested')}
    for k, e in es.items():
        if e['status'] == 'done' and k not in done:
            problems.append(f'{k} says done but is not marked integrated and tested')
    if '--check' in sys.argv:
        print('\n'.join(problems) or 'ledger OK')
        return 1 if problems else 0

    # Tick the CSV and the workbook.
    for r in rs:
        r['Got it'] = 'TRUE' if (r['Area'], r['Game id']) in done or r['Got it'].upper() == 'TRUE' else 'FALSE'
    with open(CSV, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=list(rs[0].keys()))
        w.writeheader()
        w.writerows(rs)
    try:
        import openpyxl
        wb = openpyxl.load_workbook(XLSX)
        ws = wb.worksheets[0]
        hdr = [c.value for c in ws[1]]
        ia, ii, ig = hdr.index('Area'), hdr.index('Game id'), hdr.index('Got it')
        for row in ws.iter_rows(min_row=2):
            if (row[ia].value, row[ii].value) in done:
                row[ig].value = True
        wb.save(XLSX)
    except Exception as ex:  # noqa: BLE001
        problems.append(f'workbook not updated: {ex}')

    # Manifest.
    by_area = defaultdict(list)
    for r in rs:
        by_area[r['Area']].append(r)
    lines = ['# Asset manifest', '', 'Generated by `tools/assets/ledger.py` from `docs/assets/ledger/*.json`. One line per spreadsheet row that has had work.', '']
    lines.append('| Area | Name | Game id | Requirement | Status | Files | Format | Source | Licence | Origin | Optimised | Integrated | Tested | Package | Notes |')
    lines.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    yn = lambda v: 'yes' if v else 'no'
    for area, lst in by_area.items():
        for r in lst:
            e = es.get((area, r['Game id']))
            if not e:
                continue
            files = '<br>'.join(f'`{p}`' for p in e.get('files', []))
            lines.append(f"| {area} | {r['Name']} | `{r['Game id']}` | {r['Asset needed']} | {e['status']} | {files} | {e.get('format','')} | {e.get('source','')} | {e.get('licence','')} | {e.get('origin','')} | {yn(e.get('optimised'))} | {yn(e.get('integrated'))} | {yn(e.get('tested'))} | {e['package']} | {e.get('notes','').replace('|','/')} |")
    open(os.path.join(OUT, 'ASSET_MANIFEST.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

    # Statistics block for the progress file.
    st = Counter(e['status'] for e in es.values())
    orig = sum(1 for k in done if es[k].get('origin') == 'original')
    dl = sum(1 for k in done if es[k].get('origin') == 'downloaded')
    stats = [
        '<!-- stats:start (generated by tools/assets/ledger.py) -->',
        f'- Spreadsheet rows: **{len(rs)}**',
        f'- Ticked (Got it = TRUE): **{sum(1 for r in rs if r["Got it"] == "TRUE")}**',
        f'- Done this production (integrated and tested): **{len(done)}** ({dl} from downloaded packs, {orig} made originally)',
        f'- Partly done: **{st["partial"]}**, blocked: **{st["blocked"]}**',
        f'- Still to start: **{len(rs) - len(es)}**',
        '',
        '| Area | Rows | Done | Partial |',
        '|---|---|---|---|',
    ]
    for area, lst in by_area.items():
        d = sum(1 for r in lst if (area, r['Game id']) in done)
        p = sum(1 for r in lst if es.get((area, r['Game id']), {}).get('status') == 'partial')
        stats.append(f'| {area} | {len(lst)} | {d} | {p} |')
    stats.append('<!-- stats:end -->')
    prog = os.path.join(OUT, 'ASSET_PROGRESS.md')
    txt = open(prog, encoding='utf-8').read() if os.path.exists(prog) else '# Asset progress\n\n<!-- stats:start --><!-- stats:end -->\n'
    a, b = txt.index('<!-- stats:start'), txt.index('<!-- stats:end -->') + len('<!-- stats:end -->')
    open(prog, 'w', encoding='utf-8').write(txt[:a] + '\n'.join(stats) + txt[b:])
    print(f'{len(done)} done, {st["partial"]} partial, {len(rs) - len(es)} untouched')
    if problems:
        print('PROBLEMS:\n' + '\n'.join(problems))
    return 0


if __name__ == '__main__':
    sys.exit(main())
