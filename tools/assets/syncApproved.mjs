// Copies the approved asset sources into the game, unchanged, with a header that skips the game's strict type checks.
// The originals (assets/streetassettesting/*.ts, newassetsfromchatgpt.ts) are never edited: run this after one changes.
//   node tools/assets/syncApproved.mjs
// tests/approvedAssets.test.ts fails if a copy differs from its original.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
export const HEADER = '// @ts-nocheck\n// GENERATED by tools/assets/syncApproved.mjs from the approved original. Do not edit: edit the original and run the script.\n';
export const SOURCES = {
  'batch01.ts': 'assets/streetassettesting/batch01.ts',
  'batch02.ts': 'assets/streetassettesting/batch02.ts',
  'batch04.ts': 'assets/streetassettesting/batch04.ts',
  'batch05.ts': 'assets/streetassettesting/batch05.ts',
  'batch07.ts': 'assets/streetassettesting/batch07.ts',
  'streetLibrary.ts': 'newassetsfromchatgpt.ts',
  'furniture.ts': 'assets/streetassettesting/interior-furniture-megapack.ts',
  'expansion.ts': 'assets/streetassettesting/gym-security-neighbourhood-expansion.ts',
  'telephone.ts': 'assets/streetassettesting/black-desk-telephone.ts',
};
const OUT = 'src/render/approved/sources';
if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(OUT, { recursive: true });
  for (const [to, from] of Object.entries(SOURCES)) writeFileSync(`${OUT}/${to}`, HEADER + readFileSync(from, 'utf8'));
  console.log('synced', Object.keys(SOURCES).length, 'approved sources');
}
