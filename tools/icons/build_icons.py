#!/usr/bin/env python3
"""
UI icon set: public/icons/ui/<name>.svg -> src/ui/iconArt.ts

The SVG files are the artwork (original, drawn for Street Fight UK). Every file
uses the same root: viewBox 0 0 24 24, fill none, stroke currentColor,
stroke-width 2, square caps, mitred corners. Children carry no stroke or colour
attributes of their own, so the map can restyle them (it embeds the inner paths).

The game needs the shapes synchronously (icons are built into HTML strings and
into the map's SVG), so this script copies each file's inner markup into
src/ui/iconArt.ts. Run it after adding or editing an SVG:

    python3 tools/icons/build_icons.py

tests/icons.test.ts fails if the generated file and the folder disagree.
"""
import os, re, json

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'public', 'icons', 'ui')
OUT = os.path.join(ROOT, 'src', 'ui', 'iconArt.ts')
ROOT_ATTRS = {
    'viewBox': '0 0 24 24', 'fill': 'none', 'stroke': 'currentColor',
    'stroke-width': '2', 'stroke-linecap': 'square', 'stroke-linejoin': 'miter',
}
BANNED = re.compile(r'\b(stroke|stroke-width|stroke-linecap|stroke-linejoin|fill|color|style|class|transform)=')


def inner(name: str) -> str:
    text = open(os.path.join(SRC, name + '.svg'), encoding='utf-8').read().strip()
    m = re.fullmatch(r'<svg([^>]*)>(.*)</svg>', text, re.S)
    if not m:
        raise SystemExit(f'{name}.svg: not a single <svg> element')
    attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', m.group(1)))
    for k, v in ROOT_ATTRS.items():
        if attrs.get(k) != v:
            raise SystemExit(f'{name}.svg: root {k}="{attrs.get(k)}", expected "{v}"')
    body = m.group(2).strip()
    if BANNED.search(body):
        raise SystemExit(f'{name}.svg: child elements must not set stroke, fill, colour, class or transform')
    return body


def main() -> None:
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith('.svg'))
    lines = [
        '// Generated by tools/icons/build_icons.py from public/icons/ui/*.svg. Do not edit by hand.',
        '// Inner markup of each 24 x 24 icon (stroke 2, square caps, mitred corners, currentColor).',
        'export const ICON_ART = {',
    ]
    for n in names:
        lines.append(f'  {json.dumps(n) if not n.isidentifier() else n}: {json.dumps(inner(n))},')
    lines.append('} as const;')
    lines.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'{len(names)} icons -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
