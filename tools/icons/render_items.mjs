#!/usr/bin/env node
/**
 * Inventory icons rendered from the items' own models.
 *
 *   node tools/icons/render_items.mjs [game-id ...]
 *
 * Renders every weapon (public/models/weapons, WEAPON_FILES in src/render/props/PropLibrary.ts)
 * and every pickup (public/models/pickups, src/render/props/pickupList.ts) with three.js in
 * headless Chrome (tools/icons/render_items.page.js): one three-quarter camera, the same
 * key/fill/rim lights, auto-fit with the same margin, long weapons on a diagonal, a soft dark
 * outline, transparent background. Writes public/icons/items/<game-id>.webp (128 px) and
 * src/ui/itemIconList.ts (the ids that have a rendered icon; itemIconUrl uses it).
 *
 * Needs three.js (THREE_DIR, default /tmp/nm/node_modules/three) and Playwright
 * (PLAYWRIGHT, default /opt/npm-tools/node_modules/playwright/index.mjs) with Chrome.
 */
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const THREE_DIR = process.env.THREE_DIR ?? '/tmp/nm/node_modules/three';
const PLAYWRIGHT = process.env.PLAYWRIGHT ?? '/opt/npm-tools/node_modules/playwright/index.mjs';
const OUT_DIR = path.join(ROOT, 'public', 'icons', 'items');
const LIST = path.join(ROOT, 'src', 'ui', 'itemIconList.ts');

/** Weapons modelled the way they're held, upside down (a chair by its back, a cone by its tip). */
const FLIP = new Set(['chair', 'cone']);

function jobs() {
  const prop = fs.readFileSync(path.join(ROOT, 'src/render/props/PropLibrary.ts'), 'utf8');
  const block = prop.match(/export const WEAPON_FILES[^=]*= \{([^}]*)\}/)[1];
  const out = [];
  for (const [, id, file] of block.matchAll(/(\w+):\s*'([^']+)'/g)) out.push({ id: `w_${id}`, url: `/public/models/weapons/${file}`, mode: FLIP.has(id) ? 'flip' : 'weapon' });
  const pick = fs.readFileSync(path.join(ROOT, 'src/render/props/pickupList.ts'), 'utf8');
  const ids = pick.match(/const ids = \[([\s\S]*?)\] as const/)[1];
  for (const [, id] of ids.matchAll(/'(\w+)'/g)) out.push({ id, url: `/public/models/pickups/${id.replace(/_/g, '-')}.glb`, mode: 'item' });
  return out;
}

const TYPES = { '.js': 'text/javascript', '.mjs': 'text/javascript', '.html': 'text/html', '.glb': 'model/gltf-binary' };
function serve() {
  const server = http.createServer((req, res) => {
    const u = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (u === '/favicon.ico') return res.writeHead(204).end();
    const file = u.startsWith('/three/') ? path.join(THREE_DIR, u.slice(7)) : path.join(ROOT, u);
    if (!file.startsWith(ROOT) && !file.startsWith(THREE_DIR)) return res.writeHead(403).end();
    fs.readFile(file, (err, data) => {
      if (err) return res.writeHead(404).end();
      res.writeHead(200, { 'content-type': TYPES[path.extname(file)] ?? 'application/octet-stream' }).end(data);
    });
  });
  return new Promise((ok) => server.listen(0, '127.0.0.1', () => ok(server)));
}

const all = jobs();
const only = process.argv.slice(2);
const todo = only.length ? all.filter((j) => only.includes(j.id)) : all;
const server = await serve();
const { chromium } = await import(PLAYWRIGHT);
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 200, height: 200 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  await page.goto(`http://127.0.0.1:${server.address().port}/tools/icons/render_items.html`);
  await page.waitForFunction(() => window.iconReady === true, null, { timeout: 30000 });
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const j of todo) {
    const data = await page.evaluate(([u, m]) => window.renderIcon(u, m), [j.url, j.mode]);
    const buf = Buffer.from(data.split(',')[1], 'base64');
    if (!data.startsWith('data:image/webp')) throw new Error(`${j.id}: browser did not encode WebP`);
    fs.writeFileSync(path.join(OUT_DIR, `${j.id}.webp`), buf);
    console.log(`${j.id.padEnd(20)} ${(buf.length / 1024).toFixed(1)} KB`);
  }
  if (errors.length) throw new Error(errors.join('\n'));
} finally {
  await browser.close();
  server.close();
}

// The list the game reads: every id with an icon file in the folder.
const have = new Set(fs.readdirSync(OUT_DIR).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)));
const ids = all.map((j) => j.id).filter((id) => have.has(id));
fs.writeFileSync(
  LIST,
  [
    '// Generated by tools/icons/render_items.mjs. Do not edit by hand.',
    '// Items with an icon rendered from their own model, in public/icons/items/<id>.webp.',
    'export const RENDERED_ICON_IDS: readonly string[] = [',
    ...ids.map((id) => `  '${id}',`),
    '];',
    '',
  ].join('\n'),
);
console.log(`${ids.length} icons -> public/icons/items, ${path.relative(ROOT, LIST)}`);
